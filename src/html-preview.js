import {createHash, randomBytes} from 'node:crypto';
import {createServer} from 'node:http';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {conversationUrl} from './commands.js';
import {findComponents, frameDocument, pageDocument, FRAME_CSP, OUTER_CSP, RESIZE_JS} from './html-components.js';

const HEADERS = {'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer', 'X-Robots-Tag': 'noindex, nofollow, noarchive',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()'};

export function splitPreviewText(text, maxBytes = 3800) {
  // Protect only URLs generated by this feature, not arbitrary input URLs.
  const tokens = text.split(/(https:\/\/[a-z0-9-]+\.trycloudflare\.com\/p\/[A-Za-z0-9_-]{43}#component-\d+)/g);
  const parts = []; let current = '', bytes = 0;
  for (let i = 0; i < tokens.length; i++) {
    const units = i % 2 && Buffer.byteLength(tokens[i]) <= maxBytes ? [tokens[i]] : [...tokens[i]];
    for (const unit of units) {
      const size = Buffer.byteLength(unit);
      if (bytes + size > maxBytes && current) { parts.push(current); current = ''; bytes = 0; }
      current += unit; bytes += size;
    }
  }
  if (current) parts.push(current);
  return parts;
}

export class HtmlPreview {
  constructor({maxPages = 128, maxBytes = 32 * 1024 * 1024} = {}) {
    this.pages = new Map(); this.decisions = new Map(); this.bytes = 0;
    this.maxPages = maxPages; this.maxBytes = maxBytes;
    this.ready = false; this.stopped = false; this.origin = null;
    this.server = null; this.process = null; this.status = 'idle'; this._stop = null;
  }
  transform(messageId, text, {sourceUrl, protectedValues = []} = {}) {
    const components = findComponents(text);
    if (!components.length) return text;
    const key = createHash('sha256').update(messageId + '\0' + text).digest('hex');
    if (this.decisions.has(key)) return this.decisions.get(key);
    let result = text;
    if (this.ready && !this.stopped && !protectedValues.some(value => typeof value === 'string' && value.length > 0 && text.includes(value))) {
      const token = randomBytes(32).toString('base64url');
      try { sourceUrl = conversationUrl(sourceUrl); } catch { sourceUrl = null; }
      const frames = components.map(component => Buffer.from(frameDocument(component.source)));
      const page = Buffer.from(pageDocument(text, components, token, sourceUrl)), original = Buffer.from(text);
      const size = page.length + original.length + frames.reduce((total, frame) => total + frame.length, 0);
      if (size <= this.maxBytes) {
        while (this.pages.size && (this.pages.size >= this.maxPages || this.bytes + size > this.maxBytes)) {
          const oldest = this.pages.keys().next().value;
          this.bytes -= this.pages.get(oldest).size; this.pages.delete(oldest);
        }
        this.pages.set(token, {page, frames, original, size}); this.bytes += size;
        const pieces = []; let cursor = 0;
        components.forEach((component, index) => {
          pieces.push(text.slice(cursor, component.start), `【HTML 组件 ${index + 1}，点击查看】\n${this.origin}/p/${token}#component-${index + 1}`);
          cursor = component.end;
        });
        pieces.push(text.slice(cursor)); result = pieces.join('');
      }
    }
    this.decisions.set(key, result);
    while (this.decisions.size > this.maxPages) this.decisions.delete(this.decisions.keys().next().value);
    return result;
  }
  response(path, method = 'GET') {
    const answer = (status, type, body, extra = {}) => ({status, headers: {...HEADERS, 'Content-Type': type, ...extra}, body: Buffer.isBuffer(body) ? body : Buffer.from(body)});
    if (method !== 'GET') return answer(405, 'text/plain; charset=utf-8', 'Method not allowed', {Allow: 'GET'});
    if (path === '/viewer.js') return answer(200, 'text/javascript; charset=utf-8', RESIZE_JS);
    const match = /^\/p\/([A-Za-z0-9_-]{43})(?:\/(source\.txt|c\/(\d{1,3})))?$/.exec(path);
    const saved = match && this.pages.get(match[1]);
    if (saved) {
      if (match[2] === 'source.txt') return answer(200, 'text/plain; charset=utf-8', saved.original,
        {'Content-Disposition': 'attachment; filename="gpt-original.txt"', 'Content-Security-Policy': "default-src 'none'; sandbox"});
      if (!match[2]) return answer(200, 'text/html; charset=utf-8', saved.page, {'Content-Security-Policy': OUTER_CSP});
      const frame = saved.frames[Number(match[3])];
      if (frame) return answer(200, 'text/html; charset=utf-8', frame, {'Content-Security-Policy': FRAME_CSP});
    }
    return answer(404, 'text/plain; charset=utf-8', '预览不存在或已经失效，请回到 GPT 原会话查看。');
  }
  async start({localOnly = false, executable, configPath, timeoutMs = 30000, spawnImpl = spawn} = {}) {
    if (this.server || this.stopped) throw new Error('preview_already_started');
    this.status = 'starting';
    const server = this.server = createServer({requestTimeout: 5000, headersTimeout: 5000}, (request, response) => {
      const result = this.response(request.url, request.method);
      response.writeHead(result.status, {...result.headers, 'Content-Length': result.body.length, Connection: 'close'});
      response.end(result.body);
    });
    server.maxConnections = 16; server.setTimeout(5000);
    this._listening = once(server, 'listening');
    server.listen(0, '127.0.0.1');
    await this._listening;
    if (this.stopped) { await this.stop(); return false; }
    this.localOrigin = `http://127.0.0.1:${server.address().port}`;
    if (localOnly) { this.origin = this.localOrigin; this.ready = true; this.status = 'ready'; return true; }
    if (!executable || !configPath) { this.status = 'unavailable'; return false; }
    // Do not inherit tunnel credentials, user cloudflared settings or logging
    // options. Only the isolated loopback preview server is exposed.
    const env = Object.fromEntries(Object.entries(process.env).filter(([key]) =>
      /^(SYSTEMROOT|WINDIR|PATH|SYSTEMDRIVE|TEMP|TMP|USERPROFILE|LOCALAPPDATA|HOME|TMPDIR|HTTPS_PROXY|HTTP_PROXY|NO_PROXY|SSL_CERT_FILE|SSL_CERT_DIR)$/i.test(key)));
    const child = this.process = spawnImpl(executable, ['tunnel', '--config', configPath, '--url', this.localOrigin,
      '--no-autoupdate', '--protocol', 'http2', '--metrics', '127.0.0.1:0'], {stdio: ['ignore', 'ignore', 'pipe'], windowsHide: true, env});
    child.on('error', () => { this.ready = false; this.status = 'unavailable'; });
    return new Promise(resolve => {
      let buffer = '', registered = false, settled = false;
      const finish = value => { if (!settled) { settled = true; clearTimeout(timer); this._finishStart = null; resolve(value); } };
      this._finishStart = finish;
      const timer = setTimeout(() => { this.status = 'unavailable'; child.kill(); finish(false); }, timeoutMs);
      child.stderr.setEncoding('utf8');
      child.stderr.on('data', data => {
        if (settled && !this.ready) return;
        buffer += data;
        let newline;
        while ((newline = buffer.indexOf('\n')) >= 0) {
          const line = buffer.slice(0, newline); buffer = buffer.slice(newline + 1);
          const url = /https:\/\/[a-z0-9-]+\.trycloudflare\.com\b/.exec(line);
          if (url) this.origin = url[0];
          if (line.includes('Registered tunnel connection')) registered = true;
          if (!this.stopped && registered && this.origin) { this.ready = true; this.status = 'ready'; finish(true); }
        }
        // No tunnel output is printed or saved; cap incomplete diagnostic lines.
        if (buffer.length > 16384) buffer = '';
      });
      const unavailable = () => { this.ready = false; this.status = this.stopped ? 'stopped' : 'unavailable'; finish(false); };
      child.once('error', unavailable); child.once('exit', unavailable);
    });
  }
  stop() {
    if (this._stop) return this._stop;
    this.stopped = true; this.ready = false; this.status = 'stopped'; this._finishStart?.(false);
    this.pages.clear(); this.decisions.clear(); this.bytes = 0;
    this._stop = (async () => {
      const child = this.process; this.process = null;
      if (child?.pid && child.exitCode === null && child.signalCode === null) {
        const exited = new Promise(resolve => child.once('exit', resolve));
        child.kill();
        const timer = setTimeout(() => child.kill('SIGKILL'), 3000);
        try { await exited; } finally { clearTimeout(timer); }
      }
      if (this.server) {
        const server = this.server; this.server = null;
        await this._listening?.catch(() => {});
        await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); });
      }
    })();
    return this._stop;
  }
}
